import test from 'node:test';
import assert from 'node:assert/strict';
import initSqlJs from 'sql.js';
import {
  INITIAL_ECOMMERCE_TABLES,
  INITIAL_DEMO_DATA,
  ORACLE_HR_TABLES,
  SQLSERVER_DBO_TABLES,
} from './sqlEngineCore';
import { preprocessDialectQuery, databaseManager } from './databaseManager';

test('sql.js can initialize in-memory SQLite and execute queries', async () => {
  const SQL = await initSqlJs();
  const db = new SQL.Database();

  const allTables = [
    ...INITIAL_ECOMMERCE_TABLES,
    ...ORACLE_HR_TABLES,
    ...SQLSERVER_DBO_TABLES,
  ];
  const created = new Set<string>();

  for (const table of allTables) {
    if (created.has(table.name)) continue;
    created.add(table.name);
    if (table.ddl) {
      db.run(table.ddl);
    }
  }

  for (const [tableName, rows] of Object.entries(INITIAL_DEMO_DATA)) {
    if (!rows.length) continue;
    const columns = Object.keys(rows[0]);
    const placeholders = columns.map(() => '?').join(', ');
    const sql = `INSERT INTO ${tableName} (${columns.join(', ')}) VALUES (${placeholders});`;

    for (const row of rows) {
      const values = columns.map((col) => row[col]);
      db.run(sql, values);
    }
  }

  const res = db.exec('SELECT * FROM customers;');
  assert.equal(res.length, 1);
  assert.equal(res[0].values.length, 8);
  assert.equal(res[0].columns[1], 'first_name');

  const empRes = db.exec('SELECT * FROM employees;');
  assert.equal(empRes.length, 1);
  assert.equal(empRes[0].values.length, 8);

  const dualRes = db.exec('SELECT dummy FROM dual;');
  assert.equal(dualRes.length, 1);
  assert.equal(dualRes[0].values[0][0], 'X');

  const logRes = db.exec('SELECT * FROM inventory_logs;');
  assert.equal(logRes.length, 1);
  assert.equal(logRes[0].values.length, 6);
});

test('preprocessDialectQuery handles T-SQL @@VERSION and @@SERVERNAME', () => {
  const ver = preprocessDialectQuery('SELECT @@VERSION');
  assert.ok(ver.syntheticResult);
  assert.equal(ver.syntheticResult.columns[0], '@@VERSION');
  assert.ok(ver.syntheticResult.rows[0]['@@VERSION'].includes('Microsoft SQL Server 2022'));

  const srv = preprocessDialectQuery('SELECT @@SERVERNAME');
  assert.ok(srv.syntheticResult);
  assert.equal(srv.syntheticResult.rows[0]['@@SERVERNAME'], 'MSSQL-PROD-AZURE-01');
});

test('preprocessDialectQuery normalizes T-SQL brackets and TOP N clause', async () => {
  const topQuery = preprocessDialectQuery('SELECT TOP 5 [o].[id], [o].[total_amount] FROM [dbo].[orders] [o]');
  assert.ok(topQuery.translatedQuery.includes('LIMIT 5'));
  assert.ok(!topQuery.translatedQuery.includes('[dbo]'));

  const res = await databaseManager.executeQuery(
    'SELECT TOP 5 [log_id], [product_id], [reason], GETDATE() AS [queried_at] FROM [dbo].[inventory_logs] WITH (NOLOCK) ORDER BY [log_id] ASC\nGO'
  );
  assert.equal(res.error, undefined);
  assert.equal(res.rowCount, 5);
  assert.equal(res.columns[0], 'log_id');
});

test('executeQuery paginates unbounded SELECT queries in batches and loads more on offset', async () => {
  const firstBatch = await databaseManager.executeQuery(
    'SELECT * FROM products ORDER BY id ASC;',
    { offset: 0, batchSize: 4 }
  );
  assert.equal(firstBatch.error, undefined);
  assert.equal(firstBatch.rows.length, 4);
  assert.equal(firstBatch.hasMore, true);
  assert.equal(firstBatch.nextOffset, 4);
  assert.equal(firstBatch.rows[0].id, 1);

  const secondBatch = await databaseManager.executeQuery(
    'SELECT * FROM products ORDER BY id ASC;',
    { offset: firstBatch.nextOffset, batchSize: 4 }
  );
  assert.equal(secondBatch.rows.length, 4);
  assert.equal(secondBatch.hasMore, true);
  assert.equal(secondBatch.nextOffset, 8);
  assert.equal(secondBatch.rows[0].id, 5);

  const finalBatch = await databaseManager.executeQuery(
    'SELECT * FROM products ORDER BY id ASC;',
    { offset: secondBatch.nextOffset, batchSize: 4 }
  );
  assert.equal(finalBatch.rows.length, 2);
  assert.equal(finalBatch.hasMore, false);
  assert.equal(finalBatch.nextOffset, undefined);
  assert.equal(finalBatch.rows[0].id, 9);
});

test('preprocessDialectQuery normalizes Oracle DUAL and SYSDATE', () => {
  const oraQuery = preprocessDialectQuery('SELECT SYSDATE FROM "HR"."DUAL"');
  assert.ok(oraQuery.translatedQuery.includes('CURRENT_TIMESTAMP'));
  assert.ok(oraQuery.translatedQuery.includes('DUAL') || oraQuery.translatedQuery.includes('dual'));
});

test('preprocessDialectQuery translates Oracle and SQL Server DDL statements for SQLite execution', async () => {
  const SQL = await initSqlJs();
  const db = new SQL.Database();

  const oraCreate = preprocessDialectQuery(
    'CREATE TABLE "AUDIT_EVENTS" (\n  "EVENT_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,\n  "EVENT_NAME" VARCHAR2(100) NOT NULL\n);'
  );
  db.run(oraCreate.translatedQuery);

  const oraAddCol = preprocessDialectQuery(
    'ALTER TABLE "AUDIT_EVENTS" ADD ("CREATED_BY" VARCHAR2(100) DEFAULT \'SYSTEM\');'
  );
  db.run(oraAddCol.translatedQuery);

  const oraTrunc = preprocessDialectQuery('TRUNCATE TABLE "AUDIT_EVENTS";');
  db.run(oraTrunc.translatedQuery);

  const oraDrop = preprocessDialectQuery('DROP TABLE "AUDIT_EVENTS" CASCADE CONSTRAINTS;');
  db.run(oraDrop.translatedQuery);

  const mssqlCreate = preprocessDialectQuery(
    'CREATE TABLE [dbo].[AuditEvents] (\n  [EventId] INT IDENTITY(1,1) PRIMARY KEY,\n  [EventName] NVARCHAR(100) NOT NULL\n);'
  );
  db.run(mssqlCreate.translatedQuery);

  const mssqlRenameCol = preprocessDialectQuery(
    "EXEC sp_rename '[dbo].[AuditEvents].[EventName]', 'ActionName', 'COLUMN';"
  );
  db.run(mssqlRenameCol.translatedQuery);

  const mssqlRenameTbl = preprocessDialectQuery(
    "EXEC sp_rename 'dbo.AuditEvents', 'AuditEventsV2';"
  );
  db.run(mssqlRenameTbl.translatedQuery);

  const mssqlTrunc = preprocessDialectQuery('TRUNCATE TABLE [dbo].[AuditEventsV2];');
  db.run(mssqlTrunc.translatedQuery);

  const mssqlDrop = preprocessDialectQuery(
    "IF OBJECT_ID(N'[dbo].[AuditEventsV2]', N'U') IS NOT NULL DROP TABLE [dbo].[AuditEventsV2];"
  );
  db.run(mssqlDrop.translatedQuery);
});

test('compiled VS Code extension activates and generates valid Webview HTML', async () => {
  const { createRequire } = await import('node:module');
  const path = await import('node:path');
  const require = createRequire(import.meta.url);
  const CjsModule = require('node:module');

  let registeredCommandCb: (() => void) | null = null;
  let createdPanelHtml = '';

  const vscodeMock = {
    ViewColumn: { One: 1 },
    Uri: {
      joinPath: (base: { fsPath: string }, ...segments: string[]) => ({
        fsPath: path.join(base.fsPath, ...segments),
        toString: () => `file://${path.posix.join(base.fsPath.replace(/\\/g, '/'), ...segments)}`,
      }),
      file: (p: string) => ({ fsPath: p }),
    },
    commands: {
      registerCommand: (cmd: string, cb: () => void) => {
        if (cmd === 'database-studio.open') registeredCommandCb = cb;
        return { dispose: () => {} };
      },
      executeCommand: () => {},
    },
    window: {
      activeTextEditor: undefined,
      registerWebviewViewProvider: () => ({ dispose: () => {} }),
      createWebviewPanel: () => {
        const webview = {
          _html: '',
          cspSource: 'https://file+.vscode-resource.vscode-cdn.net',
          get html() {
            return this._html;
          },
          set html(val: string) {
            this._html = val;
            createdPanelHtml = val;
          },
          asWebviewUri: (uri: { fsPath: string }) =>
            `https://file+.vscode-resource.vscode-cdn.net/${uri.fsPath.replace(/\\/g, '/')}`,
          onDidReceiveMessage: () => ({ dispose: () => {} }),
        };
        return {
          webview,
          onDidDispose: () => ({ dispose: () => {} }),
          reveal: () => {},
          dispose: () => {},
        };
      },
      showInformationMessage: () => {},
      showErrorMessage: () => {},
    },
    workspace: {
      workspaceFolders: [],
    },
  };

  const origLoad = CjsModule._load;
  CjsModule._load = function (request: string, parent: any, isMain: boolean) {
    if (request === 'vscode') return vscodeMock;
    return origLoad.call(this, request, parent, isMain);
  };

  try {
    const extPath = path.resolve(process.cwd(), 'out/extension.js');
    const ext = require(extPath);
    const subscriptions: any[] = [];
    ext.activate({
      extensionUri: { fsPath: process.cwd() },
      subscriptions,
    });

    assert.equal(subscriptions.length, 4);
    assert.ok(registeredCommandCb, 'database-studio.open command should be registered');

    (registeredCommandCb as () => void)();

    assert.ok(createdPanelHtml.includes('window.__VSCODE_VIEW_MODE__ = "editor"'));
    assert.ok(createdPanelHtml.includes('window.__VSCODE_EDITOR_CONFIG__ = {"editorType":"query"'));
    assert.ok(createdPanelHtml.includes('<base href="https://file+.vscode-resource.vscode-cdn.net/'));
    assert.ok(createdPanelHtml.includes('http-equiv="Content-Security-Policy"'));
    assert.ok(createdPanelHtml.includes("script-src 'nonce-"));
    assert.ok(!createdPanelHtml.includes('fonts.googleapis.com'));
  } finally {
    CjsModule._load = origLoad;
  }
});

