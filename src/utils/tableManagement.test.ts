import test from 'node:test';
import assert from 'node:assert/strict';
import {
  generateDropTableSql,
  generateTruncateTableSql,
  generateRenameTableSql,
  generateAddColumnSql,
  generateRenameColumnSql,
  generateDropColumnSql,
  generateCreateTableSql,
  generateCreateViewTemplateSql,
  generateCreateProcedureTemplateSql,
} from './tableManagement';

test('generateDropTableSql outputs valid DROP TABLE statement', () => {
  const sql = generateDropTableSql('customers');
  assert.equal(sql, 'DROP TABLE IF EXISTS `customers`;');
});

test('generateTruncateTableSql outputs valid DELETE statement for SQLite', () => {
  const sql = generateTruncateTableSql('orders');
  assert.equal(sql, 'DELETE FROM `orders`;');
});

test('generateRenameTableSql outputs valid ALTER TABLE RENAME TO statement', () => {
  const sql = generateRenameTableSql('users_v1', 'users_v2');
  assert.equal(sql, 'ALTER TABLE `users_v1` RENAME TO `users_v2`;');
});

test('generateAddColumnSql creates ALTER TABLE ADD COLUMN statement', () => {
  const sql = generateAddColumnSql('products', {
    name: 'discount_pct',
    type: 'DECIMAL(4,2)',
    nullable: true,
    primaryKey: false,
    defaultValue: '0.00',
  });
  assert.equal(sql, 'ALTER TABLE `products` ADD COLUMN `discount_pct` DECIMAL(4,2) DEFAULT 0.00;');
});

test('generateRenameColumnSql outputs valid ALTER TABLE RENAME COLUMN', () => {
  const sql = generateRenameColumnSql('customers', 'city', 'billing_city');
  assert.equal(sql, 'ALTER TABLE `customers` RENAME COLUMN `city` TO `billing_city`;');
});

test('generateDropColumnSql outputs valid ALTER TABLE DROP COLUMN', () => {
  const sql = generateDropColumnSql('products', 'rating');
  assert.equal(sql, 'ALTER TABLE `products` DROP COLUMN `rating`;');
});

test('generateCreateTableSql generates complete CREATE TABLE statement', () => {
  const sql = generateCreateTableSql('audit_logs', [
    { name: 'id', type: 'INTEGER', primaryKey: true, nullable: false },
    { name: 'action', type: 'VARCHAR(100)', primaryKey: false, nullable: false },
    { name: 'details', type: 'TEXT', primaryKey: false, nullable: true },
  ]);
  assert.ok(sql.includes('CREATE TABLE `audit_logs`'));
  assert.ok(sql.includes('`id` INTEGER PRIMARY KEY'));
  assert.ok(sql.includes('`action` VARCHAR(100) NOT NULL'));
});

test('generateDropTableSql outputs Oracle CASCADE CONSTRAINTS', () => {
  const sql = generateDropTableSql('employees', true, 'oracle');
  assert.equal(sql, 'DROP TABLE "EMPLOYEES" CASCADE CONSTRAINTS;');
});

test('generateDropTableSql outputs T-SQL IF OBJECT_ID drop syntax', () => {
  const sql = generateDropTableSql('InventoryLogs', true, 'sqlserver');
  assert.equal(sql, "IF OBJECT_ID(N'[dbo].[InventoryLogs]', N'U') IS NOT NULL DROP TABLE [dbo].[InventoryLogs];");
});

test('generateTruncateTableSql outputs Oracle and SQL Server truncate statements', () => {
  const oraSql = generateTruncateTableSql('departments', 'oracle');
  assert.equal(oraSql, 'TRUNCATE TABLE "DEPARTMENTS";');

  const mssql = generateTruncateTableSql('inventory_logs', 'sqlserver');
  assert.equal(mssql, 'TRUNCATE TABLE [dbo].[inventory_logs];');
});

test('generateCreateTableSql outputs Oracle DDL with VARCHAR2 and IDENTITY', () => {
  const sql = generateCreateTableSql(
    'audit_events',
    [
      { name: 'event_id', type: 'INTEGER', primaryKey: true, nullable: false },
      { name: 'event_name', type: 'VARCHAR(100)', primaryKey: false, nullable: false },
    ],
    'oracle'
  );
  assert.ok(sql.includes('CREATE TABLE "AUDIT_EVENTS"'));
  assert.ok(sql.includes('"EVENT_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY'));
  assert.ok(sql.includes('"EVENT_NAME" VARCHAR2(100) NOT NULL'));
});

test('generateCreateTableSql outputs T-SQL DDL with NVARCHAR and INT IDENTITY', () => {
  const sql = generateCreateTableSql(
    'AuditEvents',
    [
      { name: 'EventId', type: 'INTEGER', primaryKey: true, nullable: false },
      { name: 'EventName', type: 'VARCHAR(100)', primaryKey: false, nullable: false },
    ],
    'sqlserver'
  );
  assert.ok(sql.includes('CREATE TABLE [dbo].[AuditEvents]'));
  assert.ok(sql.includes('[EventId] INT IDENTITY(1,1) PRIMARY KEY'));
  assert.ok(sql.includes('[EventName] NVARCHAR(100) NOT NULL'));
});

test('tableManagement escapes single quotes and sanitizes default values against SQL injection', () => {
  const renameSql = generateRenameTableSql("users'; DROP TABLE x; --", "safe'name", 'sqlserver');
  assert.ok(renameSql.includes("EXEC sp_rename 'dbo.users'' DROP TABLE x --', 'safe''name';"));

  const addColSql = generateAddColumnSql('products', {
    name: 'note',
    type: 'VARCHAR(50); DROP TABLE products',
    nullable: true,
    primaryKey: false,
    defaultValue: "0'; DROP TABLE products; --",
  });
  assert.ok(addColSql.includes('`note` VARCHAR(50) DEFAULT'));
  assert.ok(addColSql.includes("DEFAULT '0''; DROP TABLE products; --'"));
});

test('generateCreateViewTemplateSql and generateCreateProcedureTemplateSql produce dialect-aware scripts', () => {
  const pgView = generateCreateViewTemplateSql('public', 'postgres');
  assert.ok(pgView.includes('CREATE OR REPLACE VIEW "public"."new_view" AS'));

  const mssqlView = generateCreateViewTemplateSql('dbo', 'sqlserver');
  assert.ok(mssqlView.includes('CREATE OR ALTER VIEW [dbo].[new_view]'));

  const pgProc = generateCreateProcedureTemplateSql('public', 'postgres');
  assert.ok(pgProc.includes('CREATE OR REPLACE PROCEDURE "public"."new_procedure"()'));
  assert.ok(pgProc.includes('LANGUAGE plpgsql'));

  const oraProc = generateCreateProcedureTemplateSql('hr', 'oracle');
  assert.ok(oraProc.includes('CREATE OR REPLACE PROCEDURE "HR"."NEW_PROCEDURE"'));
});
